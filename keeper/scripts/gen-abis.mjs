// Extracts ABIs from Foundry artifacts into a typed TS module (`as const`)
// so viem infers argument/return types. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";
const contracts = {
  meridian: "Meridian.sol/Meridian.json",
  vault: "CuratorVault.sol/CuratorVault.json",
  flashLiquidator: "FlashLiquidator.sol/FlashLiquidator.json",
  irm: "AdaptiveCurveIrm.sol/AdaptiveCurveIrm.json",
  erc20: "Mocks.sol/MockERC20.json",
  mockOracle: "Mocks.sol/MockOracle.json",
  navOracle: "NavOracle.sol/NavOracle.json",
};
let out = "// AUTO-GENERATED by scripts/gen-abis.mjs — do not edit.\n\n";
for (const [name, path] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(new URL(`../../out/${path}`, import.meta.url)));
  out += `export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
for (const target of ["../src/abis.ts", "../../dashboard/src/abis.ts"]) {
  try { writeFileSync(new URL(target, import.meta.url), out); console.log("wrote", target); }
  catch { /* dashboard may not exist yet */ }
}
